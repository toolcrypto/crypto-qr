// Regenerates src/logos/marks.ts from the icons of @web3icons/core: `npm run logos`.
//
// The marks are taken as they are, in their own colours. Each one is turned
// from markup into data, a list of filled paths, which is all these icons are
// made of. Anything else in an icon stops the script.
import { readFile, writeFile } from 'node:fs/promises'

/**
 * Export name to icon: a chain goes by its id, a token by its ticker in
 * lowercase. An icon that only exists in white comes with the colour to give it.
 */
const SOURCES = {
  bitcoin: 'networks/branded/bitcoin',
  litecoin: 'networks/branded/litecoin',
  // The Dogecoin coin is a 25 kB drawing. Its letter stands in, in the coin's gold.
  dogecoin: ['tokens/mono/DOGE', '#C2A633'],
  zcash: 'tokens/branded/ZEC',
  bitcoincash: 'tokens/branded/BCH',
  xrp: ['networks/mono/xrp', '#23292F'],
  monero: 'tokens/branded/XMR',
  stellar: 'networks/branded/stellar',
  ethereum: 'networks/branded/ethereum',
  optimism: 'networks/branded/optimism',
  bsc: 'networks/branded/binance-smart-chain',
  polygon: 'networks/branded/polygon',
  base: 'networks/branded/base',
  arbitrum: 'networks/branded/arbitrum-one',
  avalanche: 'networks/branded/avalanche',
  cardano: 'networks/branded/cardano',
  tron: 'networks/branded/tron',
  solana: 'networks/branded/solana',
  ton: 'networks/branded/ton',
  usdt: 'tokens/branded/USDT',
  usdc: 'tokens/branded/USDC',
}

/** The attributes each element may have. An icon with anything more needs a look. */
const KNOWN = {
  svg: ['xmlns', 'width', 'height', 'fill', 'viewBox', 'class'],
  path: ['fill', 'd', 'fill-rule', 'clip-rule'],
  defs: [],
  linearGradient: ['id', 'x1', 'x2', 'y1', 'y2', 'gradientUnits'],
  stop: ['offset', 'stop-color'],
}

/** Splits an icon into its opening tags, each with its attributes. */
function elements(svg, icon) {
  return [...svg.matchAll(/<(\w+)((?:\s+[\w:-]+="[^"]*")*)\s*\/?>/g)].map(([, name, list]) => {
    const attributes = Object.fromEntries(
      [...list.matchAll(/([\w:-]+)="([^"]*)"/g)].map(([, key, value]) => [key, value]),
    )
    const unknown = Object.keys(attributes).filter((key) => !KNOWN[name]?.includes(key))
    if (!KNOWN[name] || unknown.length) throw new Error(`${icon}: unexpected <${name} ${unknown}>`)
    return { name, ...attributes }
  })
}

/** The filled paths of an icon, each with its colour or its gradient. */
function paths(svg, icon, recolour) {
  const tags = elements(svg, icon)
  if (tags[0]?.viewBox !== '0 0 24 24') throw new Error(`${icon}: not on a 24-unit grid`)
  const gradients = new Map()
  for (const [at, tag] of tags.entries()) {
    if (tag.name === 'linearGradient') {
      if (tag.gradientUnits !== 'userSpaceOnUse') throw new Error(`${icon}: gradient units`)
      gradients.set(tag.id, { from: [+tag.x1, +tag.y1], to: [+tag.x2, +tag.y2], stops: [] })
    }
    if (tag.name === 'stop') {
      const owner = tags.slice(0, at).findLast((before) => before.name === 'linearGradient')
      gradients.get(owner.id).stops.push([+(tag.offset ?? 0), tag['stop-color']])
    }
  }
  return tags
    .filter((tag) => tag.name === 'path')
    .map((tag) => {
      const reference = /^url\(#(.+)\)$/.exec(tag.fill)?.[1]
      const fill = recolour ?? (reference ? gradients.get(reference) : tag.fill)
      if (!fill) throw new Error(`${icon}: a path has no fill`)
      return { fill, ...(tag['fill-rule'] === 'evenodd' && { evenOdd: true }), d: tag.d }
    })
}

const manifest = new URL('../node_modules/@web3icons/core/package.json', import.meta.url)
const { version } = JSON.parse(await readFile(manifest, 'utf8'))

const logos = await Promise.all(
  Object.entries(SOURCES).map(async ([name, source]) => {
    const [icon, recolour] = [source].flat()
    const { default: svg } = await import(`@web3icons/core/svgs/${icon}.svg.js`)
    const logo = { paths: paths(svg, icon, recolour) }
    return `export const ${name}Logo: VectorLogo = ${JSON.stringify(logo, null, 2)}`
  }),
)

const notice =
  `Logos from web3icons ${version}, MIT License, Copyright (c) 2024 0xa3k5: ` +
  'https://github.com/0xa3k5/web3icons'

// The first comment is kept in what is built and bundled; the formatter does the rest.
const header = `/*! ${notice} */

// Generated by scripts/logos.mjs. Do not edit.
import type { VectorLogo } from '../qr/logo.js'`

await writeFile(
  new URL('../src/logos/marks.ts', import.meta.url),
  `${[header, ...logos].join('\n\n')}\n`,
)
console.log(`${logos.length} logos from @web3icons/core ${version}`)
